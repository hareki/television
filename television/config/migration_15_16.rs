use anyhow::Result;
use std::path::Path;
use tracing::{debug, warn};

use super::CONFIG_FILE_NAME;

const STAMP_FILE_NAME: &str = ".migrated-0.15-0.16-config";
const BACKUP_FILE_NAME: &str = "config.toml.0.15.bak";

/// Settings that shape the look of the UI that was refactored in 0.16. They
/// are dropped whatever their value so that every 0.15 user gets the new look.
const STALE_SETTINGS: &[&[&str]] = &[
    &["ui", "theme"],
    &["ui", "input_bar", "prompt"],
    &["ui", "input_bar", "border_type"],
    &["ui", "status_bar", "separator_open"],
    &["ui", "status_bar", "separator_close"],
    &["ui", "results_panel", "border_type"],
    &["ui", "preview_panel", "scrollbar"],
    &["ui", "preview_panel", "border_type"],
    &["keybindings", "tab"],
    &["keybindings", "backtab"],
];

/// Remove stale 0.15 settings from the user's config file on the first 0.16 run
pub fn migrate_0_15_config_once(config_dir: &Path, data_dir: &Path) {
    let stamp_path = data_dir.join(STAMP_FILE_NAME);
    if stamp_path.exists() {
        return;
    }
    let config_file = config_dir.join(CONFIG_FILE_NAME);
    match remove_stale_settings(&config_file) {
        Ok(removed) if removed.is_empty() => {
            debug!("config migration: nothing to do");
        }
        Ok(removed) => {
            debug!(
                "config migration: removed {} stale settings from {:?}: {:?}",
                removed.len(),
                config_file,
                removed
            );
            eprintln!("tv: config migrated to 0.16.");
        }
        Err(e) => {
            warn!(
                "config migration: failed to migrate {:?} to 0.16: {e}",
                config_file
            );
            return;
        }
    }
    let _ = std::fs::write(&stamp_path, b"");
}

/// this returns the toml paths of the removed settings
fn remove_stale_settings(config_file: &Path) -> Result<Vec<String>> {
    if !config_file.is_file() {
        return Ok(Vec::new());
    }
    let contents = std::fs::read_to_string(config_file)?;
    let mut toml_settings: toml::Table = toml::from_str(&contents)?;

    let mut removed = Vec::new();
    for path in STALE_SETTINGS {
        if remove(&mut toml_settings, path) {
            removed.push(path.join("."));
        }
    }
    if removed.is_empty() {
        return Ok(removed);
    }

    prune_empty_tables(&mut toml_settings);
    std::fs::rename(
        config_file,
        config_file.with_file_name(BACKUP_FILE_NAME),
    )?;
    if toml_settings.is_empty() {
        debug!(
            "config migration: nothing left, not writing a new config file"
        );
    } else {
        std::fs::write(
            config_file,
            format!(
                "# This file was generated by tv upon upgrade, original backed up as \
                 {BACKUP_FILE_NAME}\n\n{}",
                toml::to_string_pretty(&toml_settings)?
            ),
        )?;
    }
    Ok(removed)
}

/// Drops the tables left empty by the removals.
fn prune_empty_tables(table: &mut toml::Table) {
    table.retain(|_, value| match value {
        toml::Value::Table(child) => {
            prune_empty_tables(child);
            !child.is_empty()
        }
        _ => true,
    });
}

fn remove(table: &mut toml::Table, path: &[&str]) -> bool {
    let (key, parents) = path.split_last().expect("paths are never empty");
    parents
        .iter()
        .try_fold(table, |node, parent| node.get_mut(*parent)?.as_table_mut())
        .and_then(|node| node.remove(*key))
        .is_some()
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    // the default config tv 0.15 wrote on first run
    const CONFIG_0_15: &str = include_str!("fixtures/config_0_15.toml");

    #[test]
    fn removes_stale_settings_whatever_their_value() {
        let config_dir = tempdir().unwrap();
        let data_dir = tempdir().unwrap();
        let config_file = config_dir.path().join(CONFIG_FILE_NAME);
        let contents = CONFIG_0_15
            .replace(r#"theme = "default""#, r#"theme = "tokyonight""#);
        std::fs::write(&config_file, &contents).unwrap();

        migrate_0_15_config_once(config_dir.path(), data_dir.path());

        let backup = config_dir.path().join(BACKUP_FILE_NAME);
        assert_eq!(std::fs::read_to_string(backup).unwrap(), contents);
        let migrated: toml::Table =
            toml::from_str(&std::fs::read_to_string(&config_file).unwrap())
                .unwrap();
        assert!(migrated["ui"].get("theme").is_none());
        assert!(migrated["ui"]["preview_panel"].get("border_type").is_none());
        assert!(migrated["keybindings"].get("tab").is_none());
        // other settings are left alone
        assert_eq!(migrated["ui"]["ui_scale"].as_integer(), Some(100));
    }

    #[test]
    fn leaves_other_configs_untouched() {
        let config_dir = tempdir().unwrap();
        let data_dir = tempdir().unwrap();
        let config_file = config_dir.path().join(CONFIG_FILE_NAME);
        let contents = "[ui]\nui_scale = 80\n";
        std::fs::write(&config_file, contents).unwrap();

        migrate_0_15_config_once(config_dir.path(), data_dir.path());

        assert_eq!(std::fs::read_to_string(&config_file).unwrap(), contents);
        assert!(!config_dir.path().join(BACKUP_FILE_NAME).exists());
    }

    #[test]
    fn removes_config_file_left_empty() {
        let config_dir = tempdir().unwrap();
        let data_dir = tempdir().unwrap();
        let config_file = config_dir.path().join(CONFIG_FILE_NAME);
        std::fs::write(
            &config_file,
            "[ui]\ntheme = \"tokyonight\"\n\n[ui.input_bar]\nborder_type = \"plain\"\n",
        )
        .unwrap();

        migrate_0_15_config_once(config_dir.path(), data_dir.path());

        assert!(!config_file.exists());
        assert!(config_dir.path().join(BACKUP_FILE_NAME).is_file());
    }

    #[test]
    fn runs_only_once() {
        let config_dir = tempdir().unwrap();
        let data_dir = tempdir().unwrap();
        let config_file = config_dir.path().join(CONFIG_FILE_NAME);

        // a first run without a config file still counts
        migrate_0_15_config_once(config_dir.path(), data_dir.path());
        std::fs::write(&config_file, CONFIG_0_15).unwrap();
        migrate_0_15_config_once(config_dir.path(), data_dir.path());

        assert_eq!(
            std::fs::read_to_string(&config_file).unwrap(),
            CONFIG_0_15
        );
    }
}
